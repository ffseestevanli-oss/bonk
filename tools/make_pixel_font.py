"""Build Bonk Pixel, Bonk's own low-resolution interface font, as a TrueType file.

Every glyph is drawn here as rows of pixels: 5 rows for capitals (rows 0-4,
row 4 sitting on the baseline) and 2 more below for descenders (rows 5-6).
The em is 6 pixels, so the font is pixel-exact at 6 px (and 12, 18…).

    python3 tools/make_pixel_font.py assets/fonts/BonkPixel.ttf

Needs fontTools. The font is original work, released with Bonk under the
GPL-3.0-or-later with the font exception (see assets/fonts/README.md).
"""
